def compute_centroid(rings: list[list[tuple[float, float]]]) -> tuple[float, float]:
    # Centroid of first (largest) polygon ring in SVG coords
    pts = [proj(lon, lat) for lon, lat in rings[0]]
    cx = round(sum(p[0] for p in pts) / len(pts), 1)
    cy = round(sum(p[1] for p in pts) / len(pts), 1)
    return cx, cy


def main() -> None:
    entries = []
    for code, rings in PROVINCE_RINGS.items():
        d = rings_to_d(rings)
        cx, cy = compute_centroid(rings)
        entries.append(f'  {code}: {{ d: "{d}", cx: {cx}, cy: {cy} }}')

    content = (
        "// Peta SVG Geografis 38 Provinsi Indonesia (termasuk 4 DOB Papua) pada viewBox 0 0 1100 430\n"
        "// Proyeksi ekuirektangular dari koordinat geografis Indonesia (94.5°BT–141.5°BT, 6.5°LU–11°LS)\n\n"
        "export interface ProvinceSvgGeometry {\n"
        "  d: string;\n"
        "  cx: number;\n"
        "  cy: number;\n"
        "}\n\n"
        "export const PROVINCE_SVG_PATHS: Record<string, ProvinceSvgGeometry> = {\n"
        + ",\n".join(entries)
        + "\n};\n"
    )
    OUT_PATH.write_text(content, encoding="utf-8")
    print(f"Generated {len(PROVINCE_RINGS)} province SVG paths -> {OUT_PATH}")


if __name__ == "__main__":
    main()
