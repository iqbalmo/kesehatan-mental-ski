"""
Generate geographically accurate SVG paths for all 38 Indonesian provinces (including 4 Papua DOBs)
using equirectangular projection x = (lon - 94.5) * 23, y = (6.5 - lat) * 23 in a 1100x430 viewBox.
"""

from pathlib import Path

OUT_PATH = Path(__file__).resolve().parent.parent / "src" / "data" / "indonesia-38-map-paths.ts"


def proj(lon: float, lat: float) -> tuple[float, float]:
    return round((lon - 94.5) * 23.0, 1), round((6.5 - lat) * 23.0, 1)


def rings_to_d(rings: list[list[tuple[float, float]]]) -> str:
    parts = []
    for ring in rings:
        pts = [proj(lon, lat) for lon, lat in ring]
        d = f"M{pts[0][0]},{pts[0][1]} " + " ".join(f"L{x},{y}" for x, y in pts[1:]) + " Z"
        parts.append(d)
    return " ".join(parts)


